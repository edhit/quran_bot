export function nudgeText(missedDays: number, debt: number): string {
  const base = NUDGES[Math.min(missedDays, NUDGES.length - 1)];
  return debt > 0 ? `${base}\n\n❗️ Накопилось невыполненных заданий: ${debt}.` : base;
}

