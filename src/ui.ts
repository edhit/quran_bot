export function taskButtons(
  taskId: number,
  opts: { audio?: boolean } = {}
): Button[][] {
  const rows: Button[][] = [
    [
      { text: "🎙 Прочитать", data: `rec:${taskId}` },
      { text: "👁 Показать текст", data: `txt:${taskId}` },
    ],
  ];
  if (opts.audio !== false) {
    rows.push([
      { text: "🎧 Слушать", data: `aud:${taskId}` },
      { text: "🌍 Перевод", data: `trn:${taskId}` },
    ]);
  }
  rows.push([
    { text: "✅ Выучил / повторил", data: `done:${taskId}` },
    { text: "⏭ Позже", data: `skip:${taskId}` },
  ]);
  return rows;
}

